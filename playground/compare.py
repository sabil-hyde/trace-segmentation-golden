"""One table over every run: quality, speed, cost, failures and the configuration that produced them.

    python -m playground.compare          # prints and writes runs/COMPARISON.md
"""

from __future__ import annotations

import json

from playground import RUNS_DIR


def rows():
    for path in sorted(RUNS_DIR.glob("*/metrics.json")):
        m = json.loads(path.read_text())
        t, q, s, c, r = m["task"], m["quality"], m["speed"], m["cost"], m["reliability"]
        if t["task"] == "seg":
            config = f"context={t['context']} t={t['threshold']}{' (fit)' if m['threshold_fit'] else ''}"
            quality = (f"F1 {q['boundary']['f1']:.3f} · P {q['boundary']['precision']:.2f} · R {q['boundary']['recall']:.2f}"
                       f" · decoy FS {q['slices']['false_split_rate_by_followup_kind'].get('decoy', {}).get('rate', 0):.0%}")
        else:
            config = f"{t['level']} ({t['n_classes']}) · {t['view']}"
            quality = (f"acc {q['accuracy']:.3f} (overlap-forgiven {q['accuracy_overlap_forgiven']:.3f}) · mF1 {q['macro_f1']:.3f}"
                       + (f" · ind {q['derived_industry_accuracy']:.3f}" if "derived_industry_accuracy" in q else ""))
        yield [m["run"][:16], t["task"], m["classifier"] + (f" ({m['model']})" if m.get("model") else ""), config,
               str(m["dataset"]["n"]), quality, f"{s['p50_latency_s']}", f"{s['p95_latency_s']}", f"{s['throughput_per_s']}",
               f"${c['total_usd']:.4f}", f"${c['per_1k_usd']}" if c["per_1k_usd"] is not None else "?", str(r["failures"])]


def main() -> None:
    head = ["run", "task", "classifier", "config", "n", "quality", "p50 s", "p95 s", "items/s", "cost", "$/1k", "fail"]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(r) + " |" for r in rows()]
    table = "\n".join(lines)
    (RUNS_DIR / "COMPARISON.md").write_text("# Runs\n\nGenerated by `python -m playground.compare`.\n\n" + table + "\n")
    print(table)


if __name__ == "__main__":
    main()
